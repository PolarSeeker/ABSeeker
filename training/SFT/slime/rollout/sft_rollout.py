import logging
import os

from slime.utils.mask_utils import MultiTurnLossMaskGenerator
from slime.utils.processing_utils import load_processor, load_tokenizer
from jinja2 import Template

__all__ = ["generate_rollout"]

logger = logging.getLogger(__name__)


TOKENIZER = None
PROCESSOR = None
MASK_GENERATOR = None
JINJA_PTH = None

SAMPLE_PRINTED = False


def generate_rollout(args, rollout_id, data_buffer, evaluation=False):
    """An example to implement the generate_rollout function for an rule based rm rollout generation.

    Args:
        args: the whole args
        rollout_id: int, the id of the rollout, used for deterministic data generation
        data_buffer: the data buffer to store the generated samples
        evaluation: bool, whether the rollout is for evaluation or not

    Returns:
        list[Sample]: a list of samples generated by the rollout
    """
    assert not evaluation
    assert args.rollout_global_dataset

    total = args.num_rollout
    if total is None and getattr(args, "num_epoch", None):
        rpe = len(data_buffer) // args.rollout_batch_size
        total = rpe * args.num_epoch
    cur = rollout_id + 1
    if total is not None and total > 0:
        w = 20
        filled = (cur * w + total - 1) // total
        bar = "#" * filled + "-" * (w - filled)
        msg = f"sft_rollout [{bar}] rollout {cur}/{total} (id={rollout_id})"
        ne = getattr(args, "num_epoch", None)
        if ne and ne > 0 and total % ne == 0:
            rpe = total // ne
            msg += f", epoch {rollout_id // rpe + 1}/{ne} ({rollout_id % rpe + 1}/{rpe} in epoch)"
        logger.info(msg)
    else:
        logger.info(f"sft_rollout rollout_id={rollout_id} (num_rollout={total})")

    global TOKENIZER, PROCESSOR, MASK_GENERATOR, SAMPLE_PRINTED
    if TOKENIZER is None:
        TOKENIZER = load_tokenizer(args.hf_checkpoint, trust_remote_code=True)

    if PROCESSOR is None:
        PROCESSOR = load_processor(args.hf_checkpoint, trust_remote_code=True)

    global JINJA_PTH

    if JINJA_PTH is None:
        JINJA_PTH = os.environ.get(
            "JINJA_PTH",
            os.path.join(os.path.dirname(__file__), "..", "..", "qwen3_5_template.jinja"),
        )

    with open(JINJA_PTH, 'r') as f:
        chat_template = f.read()

    TOKENIZER.chat_template = chat_template

    if MASK_GENERATOR is None:
        MASK_GENERATOR = MultiTurnLossMaskGenerator(TOKENIZER, tokenizer_type=args.loss_mask_type)

    samples = data_buffer.get_samples(args.rollout_batch_size)

    for i, sample in enumerate(samples):
        (sample,) = sample
        messages = sample.prompt
        if getattr(args, "use_score_weight", False) and (scores := sample.metadata.get("score")):
            score_idx = 0
            weighted_messages = []
            for message in messages:
                msg = dict(message)
                if msg.get("role") == "assistant" and score_idx < len(scores):
                    msg["step_weight"] = scores[score_idx]
                    score_idx += 1
                weighted_messages.append(msg)
            messages = weighted_messages
        tools = sample.metadata.get("tools", None)

        token_ids, loss_mask = MASK_GENERATOR.get_loss_mask(messages, tools=tools)

        response_length = MASK_GENERATOR.get_response_lengths([loss_mask])[0]

        sample.tokens = token_ids
        sample.response_length = response_length
        sample.reward = 0
        sample.loss_mask = loss_mask[-response_length:]

        # breakpoint()

        if i == 0 and not SAMPLE_PRINTED:
            rendered = TOKENIZER.apply_chat_template(
                messages, tokenize=False, tools=tools,
            )
            logger.info(
                "sft_rollout applied template (%s), first sample:\n%s",
                JINJA_PTH,
                rendered,
            )
            SAMPLE_PRINTED = True

    return samples
